const dicts: Record<Lang, Record<TKey, string>> = { en, id };

export function t(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s: string = dicts[lang]?.[key] ?? en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}

/** Translator bound to the current workspace language */
export function useT() {
  const db = useDB();
  const lang: Lang = db?.settings.language ?? "en";
  return (key: TKey, vars?: Record<string, string | number>) => t(lang, key, vars);
}
